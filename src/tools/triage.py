# 任何向患者推荐的科室都必须属于此集合，杜绝「瞎定义科目」。
_KNOWN_DEPARTMENTS = {
    "神经内科",
    "呼吸内科",
    "消化内科",
    "感染科",
    "皮肤科",
    "心血管内科",
    "口腔科",
}


def _normalize_department(text: str) -> str:
    """把知识库 / 外部来源的「推荐科室」收敛到系统已定义的标准科室。

    只保留白名单内出现的科室名；若全部非法或为空，返回空串，
    由调用方回退到数据库权威映射（SymptomDeptMap）。
    """
    if not text:
        return ""
    hits = [d for d in _KNOWN_DEPARTMENTS if d in text]
    return " / ".join(hits)


