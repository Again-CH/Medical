def _web_search_best_effort(query: str, timeout: int = 3) -> Optional[str]:
    """Best-effort 网络搜索：尝试通过搜索引擎获取医疗信息。

    超时或异常时返回 None（不阻塞主流程），由 LLM 知识兜底。
    """
    q = urllib.parse.quote(query)
    # 尝试百度搜索（国内可达性最好）
    url = f"https://www.baidu.com/s?wd={q}"
    try:
        ctx = ssl.create_default_context()
        req = urllib.request.Request(
            url,
            headers={"User-Agent": "Mozilla/5.0 (Macintosh; Intel Mac OS X 10_15_7)"},
        )
        with urllib.request.urlopen(req, timeout=timeout, context=ctx) as resp:
            raw = resp.read().decode("utf-8", errors="ignore")
        # 从百度结果页粗提取文本片段
        texts = re.findall(r"(?<=>)([^<]{40,500})(?=<)", raw)
        results = []
        for t in texts[:8]:
            clean = html.unescape(t).strip()
            # 过滤掉 JS 代码和无意义内容
            if clean and not clean.startswith(
                ("var ", "function", "window", "document", "//", "/*", "location.")
            ):
                if any(
                    kw in clean
                    for kw in [
                        "治疗",
                        "症状",
                        "原因",
                        "建议",
                        "科室",
                        "医院",
                        "挂号",
                        "医生",
                        "用药",
                        "预防",
                        "护理",
                    ]
                ):
                    results.append(clean)
        if results:
            return "\n".join(results[:3])  # 返回最相关的 3 条
    except Exception:
        pass
    return None


