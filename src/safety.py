# 否定词守卫：关键词前 3 字内出现否定词，视为「否认」（如「我没有胸痛」「不胸痛」）。
_NEG_RE = re.compile(r"(没|没有|无|不|非|别|未)(了|是)?$")


def _is_negated(text: str, kw: str) -> bool:
    idx = text.find(kw)
    if idx <= 0:
        return False
    before = text[max(0, idx - 3) : idx]
    return bool(_NEG_RE.search(before))


