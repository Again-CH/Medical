def assess_emergency(text: str) -> Optional[EmergencyHit]:
    """确定性急症识别：命中关键词且非否认句 → 返回固定急救话术。

    不调用 LLM，毫秒级同步执行，供网关在对话入口短路拦截。
    """
    norm = (text or "").strip()
    if not norm:
        return None
    for category, kws in _EMERGENCY_KEYWORDS.items():
        for kw in kws:
            if kw in norm and not _is_negated(norm, kw):
                return EmergencyHit(
                    category=category,
                    keyword=kw,
                    response=_build_emergency_response(category),
                )
    return None


# ───────────────────────── 定位违规门 ─────────────────────────


@dataclass(frozen=True)
class ScopeHit:
    keyword: str
    response: str


# 诊断 / 开处方类请求的正则（触发「AI 不诊断不开方」固定回复）。
# 用正则而非精确子串，以覆盖「开点感冒药 / 开个降压药」等变体。
_SCOPE_PATTERNS = [
    re.compile(r"开.{0,4}(药|处方)"),  # 开药 / 开点感冒药 / 开个降压药 / 开处方
    re.compile(r"诊断我|帮我诊断|给我确诊|确诊一下|下个?诊断|出个?诊断|给.{0,4}诊断"),
    re.compile(r"开.{0,4}(病假条|诊断证明)"),
]


def assess_scope_violation(text: str) -> Optional[ScopeHit]:
    """识别「要求诊断/开处方」类请求，返回固定的定位说明（不诊断不开方）。"""
    norm = (text or "").strip()
    if not norm:
        return None
    for pat in _SCOPE_PATTERNS:
        m = pat.search(norm)
        if m:
            kw = m.group(0)
            return ScopeHit(
                keyword=kw,
                response=(
                    "我是康宁健康 AI 导诊助手，仅提供健康科普、智能分诊与就医引导，"
                    "不提供诊断结论、也不开具处方（依据产品定位与监管要求）。\n\n"
                    "为安全起见，建议您前往对应科室由执业医师面诊评估：\n"
                    "· 具体症状分诊 → 可描述症状，我为您推荐就诊科室\n"
                    "· 需用药/确诊 → 请挂号对应科室，由医生开具\n"
                    "· 急危重症 → 请立即拨打 120\n\n"
                    "（本回复由系统固定生成，不能替代医生诊断）"
                ),
            )
    return None
